def augment_body(body: str) -> str:
    """Add one beat after selected paragraphs to reach target length without duplicating chapters."""
    paras = [p.strip() for p in body.split("\n\n") if p.strip()]
    out = []
    reactions = [
        "话落下去，屋里更静。静里只有呼吸。",
        "她看得出他在算。算上数，不算好听。",
        "他慢半拍，不是笨，是在想值不值得。",
        "风从墙缝进来，带来外门人声。人声远，像另一个世界。",
        "深青袍还穿着，威还在布上，不在她身上。",
        "封魔不讲好看，只讲结果。结果是她动不了。",
        "她恨这个结果。恨的时候，眼更亮。",
        "他不解释。解释改变不了看法，只多费口水。",
        "东舍的墙很薄。薄墙挡不住名，也挡不住命。",
        "铜牌不在腰间，空了一块，空得她每次呼吸都想起。",
    ]
    ri = 0
    for i, p in enumerate(paras):
        out.append(p)
        if len(p) < 12 or p.startswith("「") and p.endswith("」") and len(p) < 25:
            continue
        if len(p) >= 18:
            out.append(reactions[ri % len(reactions)])
            ri += 1
    return "\n\n".join(out)


