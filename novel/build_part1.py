def cjk(s: str) -> int:
    return len(re.findall(r"[\u4e00-\u9fff]", s))

def split_chapters(text: str):
    text = text.lstrip()
    if not text.startswith("# 封魔"):
        raise ValueError("unexpected header")
    body = text.split("\n", 1)[1].lstrip()
    chunks = re.split(r"\n---\n\n", body)
    out = []
    for i, ch in enumerate(chunks):
        ch = ch.strip()
        if not ch.startswith("## 第"):
            if i == 0 and "## 第一章" in ch:
                idx = ch.index("## 第一章")
                out.append(ch[idx:].strip())
            continue
        out.append(ch)
    return out[:10]

