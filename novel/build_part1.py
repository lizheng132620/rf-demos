def strip_meta(extra: str) -> str:
    if not extra.strip():
        return ""
    paras = [p.strip() for p in extra.split("\n\n") if p.strip()]

    def is_meta(p: str) -> bool:
        if any(m in p for m in META_MARKERS):
            return True
        if "这一章" in p or "章收在" in p or "章先" in p or "章写" in p:
            return True
        if re.search(r"第[一二三四五六七八九十]+章", p) and any(
            x in p for x in ("还想", "收在", "落，", "落前", "前，", "前夜璃", "前山道", "止于", "爆发")
        ):
            return True
        return False

    kept = [p for p in paras if not is_meta(p)]
    return "\n\n".join(kept)


def insert_expansion(chapter: str, extra: str) -> str:
    extra = extra.strip()
    if not extra:
        return chapter
    paras = [p for p in chapter.split("\n\n") if p.strip()]
    if len(paras) < 2:
        return chapter + "\n\n" + extra
    # insert before last paragraph
    return "\n\n".join(paras[:-1] + [extra] + [paras[-1]])

